/** Generate trusted, offline font data shared by browser preview and PDF. */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const families = {
	Inter: [
		[400, "Regular"],
		[600, "SemiBold"],
		[700, "Bold"],
		[800, "ExtraBold"],
	],
	Poppins: [
		[400, "Regular"],
		[600, "SemiBold"],
		[700, "Bold"],
		[800, "ExtraBold"],
	],
	"JetBrains Mono": [
		[400, "Regular"],
		[500, "Medium"],
		[700, "Bold"],
		[800, "ExtraBold"],
	],
};
const faces = [];
for (const [family, weights] of Object.entries(families)) {
	for (const [weight, suffix] of weights) {
		const extension = family === "Poppins" ? "ttf" : "woff2";
		const file = `${family.replaceAll(" ", "")}-${suffix}.${extension}`;
		const bytes = readFileSync(
			new URL(
				`packages/temporal/src/lib/proposal-export/fonts/${file}`,
				root,
			),
		);
		faces.push({
			family,
			weight,
			mime: extension === "ttf" ? "font/ttf" : "font/woff2",
			format: extension === "ttf" ? "truetype" : "woff2",
			data: bytes.toString("base64"),
		});
	}
}
const target = new URL(
	"packages/utils/lib/generated/artifact-brand-font-data.ts",
	root,
);
const output = `// Generated by scripts/generate-artifact-brand-fonts.mjs. Do not edit.\n// SIL Open Font License: see THIRD_PARTY_NOTICES.md and proposal-export/fonts/.\nexport const ARTIFACT_FONT_FACES = ${JSON.stringify(faces, null, "\t")} as const;\n`;
if (process.argv.includes("--check")) {
	if (readFileSync(target, "utf8") !== output) {
		throw new Error("Artifact font data is stale; regenerate it.");
	}
} else {
	mkdirSync(fileURLToPath(new URL(".", target)), { recursive: true });
	writeFileSync(target, output);
}
