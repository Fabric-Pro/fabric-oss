/**
 * The section shapes seeded report templates share.
 */

export interface ReportSection {
	id: string;
	title: string;
	type:
		| "text"
		| "table"
		| "ai-generated"
		| "data"
		| "raw"
		| "metrics"
		| "divider";
	config: Record<string, unknown>;
}

/**
 * Standard Report Header
 * Includes title, metadata line, and optional description
 */
export function headerSection(config: {
	titleTemplate: string;
	subtitleTemplate?: string;
	metadataTemplate?: string;
}): ReportSection {
	let template = `# ${config.titleTemplate}`;
	if (config.subtitleTemplate) {
		template += `\n\n*${config.subtitleTemplate}*`;
	}
	if (config.metadataTemplate) {
		template += `\n\n---\n\n${config.metadataTemplate}`;
	}
	return {
		id: "header",
		title: "Header",
		type: "text",
		config: { template },
	};
}

/**
 * Main Analysis Section
 * Core AI-generated content
 */
export function analysisSection(
	id: string,
	title: string,
	outputVariable: string,
	options?: { wrapperTemplate?: string },
): ReportSection {
	return {
		id,
		title,
		type: "ai-generated",
		config: {
			outputVariable,
			wrapperTemplate:
				options?.wrapperTemplate ?? `## ${title}\n\n{{content}}`,
		},
	};
}

/**
 * Standard Footer
 * Report generation info and disclaimers
 */
export function footerSection(options?: {
	includeTimestamp?: boolean;
	includeDisclaimer?: boolean;
	customNote?: string;
}): ReportSection {
	let template = "\n---\n\n";
	template += "📊 **Report Generated by Fabric**";

	if (options?.includeTimestamp !== false) {
		template += " · {{generatedAt}}";
	}

	if (options?.customNote) {
		template += `\n\n${options.customNote}`;
	}

	if (options?.includeDisclaimer) {
		template +=
			"\n\n*This report was generated using AI analysis. Please verify critical information.*";
	}

	return {
		id: "footer",
		title: "Footer",
		type: "text",
		config: { template },
	};
}
