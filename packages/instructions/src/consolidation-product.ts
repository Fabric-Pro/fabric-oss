/**
 * Which AI files of a code repository ship WITH the product, so "Move AI
 * files out" (see `./consolidation`) keeps them where they are.
 *
 * A repository can publish its own coding-tool plugin for its users: a
 * `.claude-plugin/plugin.json` whose `skills` point at `.claude/skills/`, a
 * `.claude-plugin/marketplace.json` whose plugin `source` is `./`, generated
 * skill copies for Codex under `.agents/skills/`. Those files look exactly
 * like development instructions, but moving them out of the repository
 * breaks the product's plugin. A file is marked `product` (with a reason a
 * person can read) when:
 *
 * - a plugin manifest in the repository references it: `skills`, `agents`,
 *   `commands`, `hooks`, `mcpServers`, `outputStyles` paths (a file or a
 *   folder, relative to the plugin root), plus the default component folders
 *   at the plugin root (`skills/`, `agents/`, `commands/`, `hooks/hooks.json`,
 *   `.mcp.json`). Claude Code (`.claude-plugin/plugin.json`), Codex
 *   (`.codex-plugin/plugin.json`) and Cursor (`.cursor-plugin/plugin.json`)
 *   manifests are read the same way;
 * - a marketplace manifest (`.claude-plugin/marketplace.json`,
 *   `.cursor-plugin/marketplace.json`, Codex's
 *   `.agents/plugins/marketplace.json`) lists a plugin whose relative
 *   `source` is a root in the repository: that plugin's own manifest, its
 *   inline component paths and its default component folders;
 * - it is a manifest itself (anything in a `.claude-plugin/`,
 *   `.codex-plugin/`, `.cursor-plugin/` folder, or a Codex marketplace);
 * - its first lines say it is generated by a script in the repository
 *   (`Generated by ai/build.mjs; do not edit.`): its source of truth lives
 *   in the code repository, so the copy stays with the generator. Nothing is
 *   executed; only the header text is read;
 * - it is the root `AGENTS.md` or `.mcp.json` of a repository that is itself
 *   a plugin or marketplace (a manifest at the repository root), because the
 *   plugin ships them to its users.
 *
 * Everything else keeps the plan's classification. The module is pure: the
 * caller reads the manifests and headers it names and passes their text in.
 */

import type { ConsolidationItem, ConsolidationPlan } from "./consolidation";

/** Plugin manifest folders whose `plugin.json` lists the plugin's components. */
const PLUGIN_DIRS = [".claude-plugin", ".codex-plugin", ".cursor-plugin"];

/** Codex's repository marketplace. */
const CODEX_MARKETPLACE = ".agents/plugins/marketplace.json";

/** Manifest fields whose values are component paths (a string or a list). */
const COMPONENT_FIELDS = [
	"skills",
	"agents",
	"commands",
	"hooks",
	"mcpServers",
	"outputStyles",
] as const;

/** What a plugin loads from its root without being told. */
const DEFAULT_COMPONENTS = [
	"skills",
	"agents",
	"commands",
	"hooks/hooks.json",
	".mcp.json",
];

/** Most leading characters searched for a generated-file note. */
const HEADER_CHARS = 2000;
/** Most leading lines searched for a generated-file note. */
const HEADER_LINES = 15;

/** File types whose first lines can carry a generated-file note. */
const TEXT_FILE = /\.(md|mdc|markdown|txt|json|jsonc|toml|ya?ml)$/i;

function normalize(path: string): string {
	return path.replace(/\\/g, "/").replace(/^(\.\/)+/, "");
}

function dirname(path: string): string {
	const index = path.lastIndexOf("/");
	return index === -1 ? "" : path.slice(0, index);
}

/**
 * `ref` (relative to `root`) as a repository path, or null when it leaves the
 * repository or is not a relative path (a URL, an absolute path).
 */
function resolve(root: string, ref: string): string | null {
	const trimmed = ref.trim().replace(/\\/g, "/");
	if (
		trimmed === "" ||
		trimmed.startsWith("/") ||
		/^[a-z][a-z0-9+.-]*:/i.test(trimmed)
	) {
		return null;
	}
	const out = root === "" ? [] : root.split("/");
	for (const segment of trimmed.split("/")) {
		if (segment === "" || segment === ".") {
			continue;
		}
		if (segment === "..") {
			if (out.length === 0) {
				return null;
			}
			out.pop();
			continue;
		}
		out.push(segment);
	}
	return out.join("/");
}

function within(path: string, ref: string): boolean {
	return ref === "" || path === ref || path.startsWith(`${ref}/`);
}

function parseJson(text: string | undefined): Record<string, unknown> | null {
	if (text === undefined) {
		return null;
	}
	try {
		const value: unknown = JSON.parse(text);
		return value !== null &&
			typeof value === "object" &&
			!Array.isArray(value)
			? (value as Record<string, unknown>)
			: null;
	} catch {
		return null;
	}
}

function stringsOf(value: unknown): string[] {
	if (typeof value === "string") {
		return [value];
	}
	if (Array.isArray(value)) {
		return value.filter((v): v is string => typeof v === "string");
	}
	return [];
}

function isPluginManifest(path: string): boolean {
	return PLUGIN_DIRS.some(
		(dir) =>
			path === `${dir}/plugin.json` ||
			path.endsWith(`/${dir}/plugin.json`),
	);
}

function isMarketplace(path: string): boolean {
	return (
		path === CODEX_MARKETPLACE ||
		path.endsWith(`/${CODEX_MARKETPLACE}`) ||
		PLUGIN_DIRS.some(
			(dir) =>
				path === `${dir}/marketplace.json` ||
				path.endsWith(`/${dir}/marketplace.json`),
		)
	);
}

/** A file in a manifest folder: the manifests themselves are never moved. */
function isManifestFile(path: string): boolean {
	const segments = path.split("/");
	return (
		segments.slice(0, -1).some((s) => PLUGIN_DIRS.includes(s)) ||
		isMarketplace(path)
	);
}

/** The repository paths of the manifests the detection reads. */
export function pluginManifestPaths(paths: readonly string[]): string[] {
	return paths
		.map(normalize)
		.filter((path) => isPluginManifest(path) || isMarketplace(path))
		.sort();
}

/**
 * The note of a generated file (`generated by ai/build.mjs`), or null. A
 * line among the first ones must say "generated" and name a script.
 */
export function generatedMarker(text: string): string | null {
	const lines = text
		.slice(0, HEADER_CHARS)
		.split(/\r?\n/)
		.slice(0, HEADER_LINES);
	for (const line of lines) {
		if (!/\b(auto-?)?generated\b/i.test(line)) {
			continue;
		}
		const script = line.match(
			/(?:^|[\s`'"(=:])((?:\.{1,2}\/)?[\w.-]+(?:\/[\w.-]+)*\.(?:mjs|cjs|js|mts|cts|ts|py|sh|ps1|rb|go))(?=$|[\s`'"),;:.])/i,
		);
		if (script?.[1]) {
			return `generated by ${normalize(script[1])}`;
		}
	}
	return null;
}

/**
 * The plan items whose first lines are worth reading for a generated-file
 * note: text files not already known to ship with the product (nor
 * identical copies of one), at most
 * `limit` of them, in path order.
 */
export function generatedHeaderCandidates(
	items: readonly ConsolidationItem[],
	known: ReadonlyMap<string, string>,
	limit: number,
): string[] {
	return items
		.filter(
			(item) =>
				!known.has(item.from) &&
				!(item.duplicateOf && known.has(item.duplicateOf)) &&
				TEXT_FILE.test(item.from),
		)
		.map((item) => item.from)
		.sort()
		.slice(0, limit);
}

type Ref = { path: string; reason: string };

function componentRefs(
	root: string,
	fields: Record<string, unknown>,
	usedBy: string,
): Ref[] {
	const refs: Ref[] = [];
	for (const field of COMPONENT_FIELDS) {
		for (const value of stringsOf(fields[field])) {
			const path = resolve(root, value);
			// "./" alone would claim the whole plugin root; ignore it.
			if (path !== null && path !== "") {
				refs.push({ path, reason: `used by ${usedBy} (${field})` });
			}
		}
	}
	for (const component of DEFAULT_COMPONENTS) {
		const path = resolve(root, component);
		if (path !== null) {
			refs.push({
				path,
				reason: `loaded by ${usedBy} from the plugin root`,
			});
		}
	}
	return refs;
}

function marketplaceRefs(
	path: string,
	marketplace: Record<string, unknown>,
	manifests: Readonly<Record<string, string>>,
): Ref[] {
	// `.claude-plugin/marketplace.json` -> its folder's parent;
	// `.agents/plugins/marketplace.json` -> the folder holding `.agents`.
	const root =
		path === CODEX_MARKETPLACE || path.endsWith(`/${CODEX_MARKETPLACE}`)
			? dirname(dirname(dirname(path)))
			: dirname(dirname(path));
	const metadata = marketplace.metadata as
		| Record<string, unknown>
		| undefined;
	const pluginRoot =
		typeof metadata?.pluginRoot === "string" ? metadata.pluginRoot : "";
	const refs: Ref[] = [];
	const plugins = Array.isArray(marketplace.plugins)
		? marketplace.plugins
		: [];
	for (const entry of plugins) {
		if (entry === null || typeof entry !== "object") {
			continue;
		}
		const plugin = entry as Record<string, unknown>;
		const source = plugin.source;
		const relative =
			typeof source === "string"
				? source
				: source !== null &&
						typeof source === "object" &&
						typeof (source as Record<string, unknown>).path ===
							"string"
					? ((source as Record<string, unknown>).path as string)
					: null;
		if (relative === null) {
			continue;
		}
		// A bare name is resolved under `metadata.pluginRoot`.
		const base =
			pluginRoot !== "" && !/^\.{1,2}(\/|$)/.test(relative)
				? resolve(root, pluginRoot)
				: root;
		const pluginDir = base === null ? null : resolve(base, relative);
		if (pluginDir === null) {
			continue;
		}
		const name =
			typeof plugin.name === "string" ? plugin.name : pluginDir || "./";
		const usedBy = `plugin "${name}" in ${path}`;
		refs.push(...componentRefs(pluginDir, plugin, usedBy));
		for (const dir of PLUGIN_DIRS) {
			const manifestPath = resolve(pluginDir, `${dir}/plugin.json`);
			const manifest =
				manifestPath === null
					? null
					: parseJson(manifests[manifestPath]);
			if (manifestPath !== null && manifest) {
				refs.push(
					...componentRefs(
						pluginDir,
						manifest,
						`${manifestPath} (${usedBy})`,
					),
				);
			}
		}
	}
	return refs;
}

export type ProductDetectionInput = {
	/** Every file path of the code repository (or at least the plan's). */
	paths: readonly string[];
	/** The text of each manifest `pluginManifestPaths` named; missing = unread. */
	manifests: Readonly<Record<string, string>>;
	/** The leading text of files read for a generated-file note. */
	headers?: Readonly<Record<string, string>>;
};

/** The files that ship with the product, each with the reason. */
export function detectProductFiles(
	input: ProductDetectionInput,
): Map<string, string> {
	const paths = input.paths.map(normalize);
	const manifestPaths = pluginManifestPaths(paths);
	// A plugin's own manifest names its files first; marketplaces after.
	const refs: Ref[] = [];
	for (const path of manifestPaths.filter(isPluginManifest)) {
		const json = parseJson(input.manifests[path]);
		if (json) {
			refs.push(...componentRefs(dirname(dirname(path)), json, path));
		}
	}
	for (const path of manifestPaths.filter(isMarketplace)) {
		const json = parseJson(input.manifests[path]);
		if (json) {
			refs.push(...marketplaceRefs(path, json, input.manifests));
		}
	}

	const rootManifest = manifestPaths.find(
		(path) =>
			path === CODEX_MARKETPLACE ||
			PLUGIN_DIRS.some((dir) => path.startsWith(`${dir}/`)),
	);

	const out = new Map<string, string>();
	for (const path of paths) {
		if (isManifestFile(path)) {
			out.set(
				path,
				"a plugin manifest; it stays with the plugin it describes",
			);
			continue;
		}
		const ref = refs.find((r) => within(path, r.path));
		if (ref) {
			out.set(path, ref.reason);
			continue;
		}
		const header = input.headers?.[path];
		const marker = header === undefined ? null : generatedMarker(header);
		if (marker) {
			out.set(
				path,
				`${marker}; the generator lives in the code repository`,
			);
			continue;
		}
		if (rootManifest && (path === "AGENTS.md" || path === ".mcp.json")) {
			out.set(
				path,
				`the repository is itself a plugin (${rootManifest} at its root), and the plugin ships ${path} to its users`,
			);
		}
	}
	return out;
}

export type ConsolidationReviewGroup = "development" | "product";

/** One file of the review: a plan item, which group it is in, and whether it is checked. */
export type ConsolidationReviewFile = ConsolidationItem & {
	path: string;
	group: ConsolidationReviewGroup;
	reason?: string;
	selected: boolean;
};

/**
 * The plan as the person reviews it: product files (and files kept in the
 * code repository on an earlier move) are unchecked, in their own group;
 * development files keep the plan's default.
 */
export function reviewConsolidation(
	plan: Pick<ConsolidationPlan, "items">,
	product: ReadonlyMap<string, string>,
	previouslyKept: Iterable<string> = [],
): ConsolidationReviewFile[] {
	const kept = new Set(previouslyKept);
	const reasonOf = (item: ConsolidationItem): string | undefined => {
		const own = product.get(item.from);
		if (own) {
			return own;
		}
		if (item.duplicateOf && product.has(item.duplicateOf)) {
			return `an identical copy of ${item.duplicateOf}, which ships with the product`;
		}
		if (kept.has(item.from)) {
			return "kept in the code repository when AI files were last moved out";
		}
		return undefined;
	};
	return plan.items.map((item) => {
		const reason = reasonOf(item);
		return reason === undefined
			? {
					...item,
					path: item.from,
					group: "development" as const,
					selected: item.defaultIncluded,
				}
			: {
					...item,
					path: item.from,
					group: "product" as const,
					reason,
					selected: false,
				};
	});
}
