/**
 * The preservation check of a scoped AI change of a Proposal's Main
 * (Fizzy #2946): a finding-driven revision changes only its section's own
 * lines, a chat changes only the sections it patched, and neither changes an
 * existing diagram, whoever made it. A whole-body write no person reviewed
 * may change any prose but keeps every existing diagram.
 */

import { describe, expect, it } from "vitest";
import {
	checkPreservation,
	PRESERVATION_VIOLATION,
	type PreservationScope,
	sectionFingerprint,
} from "../lib/proposal-artifact/preservation";
import {
	buildSectionMap,
	PREAMBLE_SECTION_KEY,
} from "../lib/proposal-artifact/section-hash";
import {
	type VisualSpecSummary,
	visualSourceHash,
} from "../lib/proposal-artifact/visual-identity";

const lines = (...parts: string[]) => parts.join("\n");

const STEP_ID = "k3v9q2m7x1a8c4d6";

const STEP_DIAGRAM = lines(
	"```mermaid",
	`%% fabric-visual: ${STEP_ID}`,
	"%% caption: Delivery approach",
	"flowchart LR",
	"  A[Discovery] --> B[Build]",
	"```",
);

const PERSON_DIAGRAM = lines(
	"```mermaid",
	"gantt",
	"  title Delivery",
	"  section Build",
	"  Portal :a1, 2027-01-04, 30d",
	"```",
);

const SECTIONS = {
	context: lines(
		"## 1. Context",
		"",
		"Example Org needs one onboarding portal.",
	),
	approach: lines(
		"## 2. Approach",
		"",
		"We work in short phases with a weekly demo.",
		"",
		STEP_DIAGRAM,
	),
	team: lines(
		"## 3. Team",
		"",
		"See the [team page](https://example.com/team) for the people.",
	),
	timeline: lines(
		"## 4. Timeline",
		"",
		"Twelve weeks in three phases.",
		"",
		PERSON_DIAGRAM,
	),
	commercials: lines(
		"## 5. Commercials",
		"",
		"A fixed fee per phase.",
		"",
		"![Fee table](https://example.com/fees.png)",
	),
};

const doc = (parts: Partial<typeof SECTIONS> = {}, title = "Proposal") =>
	lines(
		`# ${title} for Example Org`,
		"",
		"Prepared by the delivery team.",
		"",
		...Object.values({ ...SECTIONS, ...parts }).flatMap((section) => [
			section,
			"",
		]),
	);

/** Section 2 as a person left it after the generation. */
const PERSON_EDITED_APPROACH = SECTIONS.approach.replace(
	"a weekly demo.",
	"a weekly demo on Fridays, as agreed with the sponsor.",
);

const PREVIOUS = doc({ approach: PERSON_EDITED_APPROACH });

const SPECS: VisualSpecSummary[] = [
	{
		visualId: STEP_ID,
		sourceHash: visualSourceHash(
			STEP_DIAGRAM.split("\n").slice(1, -1).join("\n"),
		),
		kind: "flowchart",
		origin: "STEP",
	},
];

/** The key of the section whose heading reads `heading` in `markdown`. */
const keyOf = (markdown: string, heading: string) => {
	const section = buildSectionMap(markdown).sections.find(
		(entry) => entry.headingText === heading,
	);
	if (!section) {
		throw new Error(`No section "${heading}"`);
	}
	return section.key;
};

const finding = (heading: string): PreservationScope => ({
	kind: "section",
	sectionKey: keyOf(PREVIOUS, heading),
});

const check = (next: string, scope: PreservationScope, previous = PREVIOUS) =>
	checkPreservation({ previous, next, scope, visualSpecs: SPECS });

const REVISED_TIMELINE = SECTIONS.timeline.replace(
	"Twelve weeks in three phases.",
	"Twelve weeks in three phases, with a pilot in week six.",
);

describe("checkPreservation: a finding-driven revision", () => {
	it("lets the target change while a person-edited section stays as it was", () => {
		expect(
			check(
				doc({
					approach: PERSON_EDITED_APPROACH,
					timeline: REVISED_TIMELINE,
				}),
				finding("4. Timeline"),
			),
		).toEqual({ ok: true });
	});

	it("names the person-edited section when the revision also changed it", () => {
		expect(
			check(doc({ timeline: REVISED_TIMELINE }), finding("4. Timeline")),
		).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: keyOf(PREVIOUS, "2. Approach"),
				},
			],
		});
	});

	it("names a changed person-made diagram in the target as person-made", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			timeline: REVISED_TIMELINE.replace("30d", "45d"),
		});

		expect(check(next, finding("4. Timeline"))).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM,
					sectionKey: keyOf(PREVIOUS, "4. Timeline"),
					ordinal: 1,
					classification: { state: "none" },
				},
			],
		});
	});

	it("names a changed STEP diagram as generated by the visuals step", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH.replace(
				"[Build]",
				"[Build and test]",
			),
		});

		const result = check(next, finding("2. Approach"));

		expect(result).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM,
					sectionKey: keyOf(PREVIOUS, "2. Approach"),
					ordinal: 0,
					visualId: STEP_ID,
					classification: { state: "generated", origin: "STEP" },
				},
			],
		});
	});

	it("refuses a caption-only change", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH.replace(
				"caption: Delivery approach",
				"caption: How we deliver",
			),
		});

		expect(check(next, finding("2. Approach"))).toMatchObject({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM,
					visualId: STEP_ID,
				},
			],
		});
	});

	it("names only the section a diagram moved out of, since it still exists", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH.replace(STEP_DIAGRAM, ""),
			timeline: lines(REVISED_TIMELINE, "", STEP_DIAGRAM),
		});

		expect(check(next, finding("4. Timeline"))).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: keyOf(PREVIOUS, "2. Approach"),
				},
			],
		});
	});

	it("refuses a diagram dropped from the target", () => {
		const dropped = doc({
			approach: PERSON_EDITED_APPROACH,
			timeline: REVISED_TIMELINE.replace(PERSON_DIAGRAM, ""),
		});

		expect(check(dropped, finding("4. Timeline"))).toMatchObject({
			ok: false,
			violations: [
				{ code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM, ordinal: 1 },
			],
		});
	});

	it("allows a new diagram in the target", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			timeline: lines(
				REVISED_TIMELINE,
				"",
				"```mermaid",
				"pie",
				'  "Build" : 60',
				'  "Test" : 40',
				"```",
			),
		});

		expect(check(next, finding("4. Timeline"))).toEqual({ ok: true });
	});

	it("refuses a changed link destination in an untargeted section", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			team: SECTIONS.team.replace("/team", "/people"),
			timeline: REVISED_TIMELINE,
		});

		expect(check(next, finding("4. Timeline"))).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: keyOf(PREVIOUS, "3. Team"),
				},
			],
		});
	});

	it("refuses a changed image destination in an untargeted section", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			commercials: SECTIONS.commercials.replace(
				"fees.png",
				"fees-v2.png",
			),
			timeline: REVISED_TIMELINE,
		});

		expect(check(next, finding("4. Timeline"))).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: keyOf(PREVIOUS, "5. Commercials"),
				},
			],
		});
	});

	it("reads a percent-encoded destination as the same destination", () => {
		const previous = doc({
			team: SECTIONS.team.replace("/team", "/café"),
		});
		const next = doc({
			team: SECTIONS.team.replace("/team", "/caf%C3%A9"),
		});

		expect(check(next, finding("4. Timeline"), previous)).toEqual({
			ok: true,
		});
	});

	it.each([
		["renamed", "## 4. Schedule"],
		["renumbered", "## 6. Timeline"],
		["moved a level down", "### 4. Timeline"],
	])("refuses a target heading that was %s", (_label, heading) => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			timeline: REVISED_TIMELINE.replace("## 4. Timeline", heading),
		});

		expect(check(next, finding("4. Timeline"))).toMatchObject({
			ok: false,
			violations: expect.arrayContaining([
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: keyOf(PREVIOUS, "4. Timeline"),
				},
			]),
		});
	});

	it("refuses a section added inside the target", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			timeline: lines(
				REVISED_TIMELINE,
				"",
				"### Milestones",
				"",
				"Week six.",
			),
		});

		expect(check(next, finding("4. Timeline"))).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: keyOf(next, "Milestones"),
				},
			],
		});
	});

	it("refuses a section removed elsewhere", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			timeline: REVISED_TIMELINE,
			commercials: "",
		});

		expect(check(next, finding("4. Timeline"))).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: keyOf(PREVIOUS, "5. Commercials"),
				},
			],
		});
	});

	it("refuses a changed title, which belongs to no section", () => {
		const next = doc(
			{ approach: PERSON_EDITED_APPROACH, timeline: REVISED_TIMELINE },
			"Offer",
		);

		expect(check(next, finding("4. Timeline"))).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: PREAMBLE_SECTION_KEY,
				},
			],
		});
	});

	it("refuses a target the previous body does not have", () => {
		expect(
			check(PREVIOUS, { kind: "section", sectionKey: "p1:missing#0" }),
		).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: "p1:missing#0",
				},
			],
		});
	});

	it("refuses a changed diagram above the first heading", () => {
		const previous = lines(PERSON_DIAGRAM, "", SECTIONS.context, "");
		const next = lines(
			PERSON_DIAGRAM.replace("30d", "31d"),
			"",
			SECTIONS.context,
			"",
		);

		expect(
			check(
				next,
				{ kind: "section", sectionKey: keyOf(previous, "1. Context") },
				previous,
			),
		).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: PREAMBLE_SECTION_KEY,
				},
				{
					code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM,
					sectionKey: PREAMBLE_SECTION_KEY,
					ordinal: 0,
					classification: { state: "none" },
				},
			],
		});
	});
});

describe("checkPreservation: a chat change", () => {
	const patched = (...headings: string[]): PreservationScope => ({
		kind: "chat",
		patchedSectionKeys: headings.map((heading) => keyOf(PREVIOUS, heading)),
	});

	it("allows a same-heading section inserted before an untouched one", () => {
		const next = doc({
			approach: lines(
				PERSON_EDITED_APPROACH,
				"",
				"## 3. Team",
				"",
				"A second team note.",
			),
		});

		// The untouched section's key moved from occurrence 0 to 1.
		expect(keyOf(next, "3. Team")).toBe(keyOf(PREVIOUS, "3. Team"));
		expect(
			buildSectionMap(next).sections.filter(
				(section) => section.headingText === "3. Team",
			).length,
		).toBe(2);
		expect(check(next, { kind: "chat", patchedSectionKeys: [] })).toEqual({
			ok: true,
		});
	});

	it("allows a change inside the patched sections", () => {
		expect(
			check(
				doc({
					approach: PERSON_EDITED_APPROACH,
					timeline: REVISED_TIMELINE,
				}),
				patched("4. Timeline"),
			),
		).toEqual({ ok: true });
	});

	it("refuses a change outside the patched sections", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			team: SECTIONS.team.replace("the people", "everyone"),
			timeline: REVISED_TIMELINE,
		});

		expect(check(next, patched("4. Timeline"))).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.OUTSIDE_TARGET,
					sectionKey: keyOf(PREVIOUS, "3. Team"),
				},
			],
		});
	});

	it("allows a patched section deleted together with its diagram", () => {
		expect(check(doc({ approach: "" }), patched("2. Approach"))).toEqual({
			ok: true,
		});
	});

	it("refuses a patched section that kept its heading but lost its diagram", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH.replace(STEP_DIAGRAM, ""),
		});

		expect(check(next, patched("2. Approach"))).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM,
					sectionKey: keyOf(PREVIOUS, "2. Approach"),
					ordinal: 0,
					visualId: STEP_ID,
					classification: { state: "generated", origin: "STEP" },
				},
			],
		});
	});

	it("refuses a changed diagram in a patched section", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			timeline: REVISED_TIMELINE.replace("30d", "45d"),
		});

		expect(check(next, patched("4. Timeline"))).toMatchObject({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM,
					ordinal: 1,
					classification: { state: "none" },
				},
			],
		});
	});

	describe("without patched section keys", () => {
		const unscoped: PreservationScope = { kind: "chat" };

		it("lets any section's text change", () => {
			const next = doc({
				context: SECTIONS.context.replace("one", "a single"),
				team: SECTIONS.team.replace("/team", "/people"),
				timeline: REVISED_TIMELINE,
			});

			expect(check(next, unscoped)).toEqual({ ok: true });
		});

		it("allows a section deleted with its diagram", () => {
			expect(check(doc({ timeline: "" }), unscoped)).toEqual({
				ok: true,
			});
		});

		it("refuses a changed diagram", () => {
			const next = doc({
				approach: PERSON_EDITED_APPROACH,
				timeline: SECTIONS.timeline.replace("30d", "45d"),
			});

			expect(check(next, unscoped)).toMatchObject({
				ok: false,
				violations: [
					{
						code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM,
						ordinal: 1,
					},
				],
			});
		});
	});
});

describe("checkPreservation: a whole-body write no person reviewed", () => {
	const wholeBody: PreservationScope = { kind: "whole-body" };
	const unscopedChat: PreservationScope = { kind: "chat" };

	/** Section 4 under a new heading, its diagram's body changed. */
	const RENAMED_CHANGED_TIMELINE = SECTIONS.timeline
		.replace("## 4. Timeline", "## 4. Delivery timeline")
		.replace("30d", "45d");

	it("lets any section's text change", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			context: SECTIONS.context.replace("one", "a single"),
			team: SECTIONS.team.replace("/team", "/people"),
			timeline: REVISED_TIMELINE,
		});

		expect(check(next, wholeBody)).toEqual({ ok: true });
	});

	it("refuses a changed diagram under a renamed heading, which an unreviewed chat would let through", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			timeline: RENAMED_CHANGED_TIMELINE,
		});

		expect(check(next, wholeBody)).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM,
					sectionKey: keyOf(PREVIOUS, "4. Timeline"),
					ordinal: 1,
					classification: { state: "none" },
				},
			],
		});
		// The chat scope is unchanged: its renamed section reads as gone,
		// and a person reviews that diff.
		expect(check(next, unscopedChat)).toEqual({ ok: true });
	});

	it("refuses a section deleted with its diagram", () => {
		const next = doc({ approach: PERSON_EDITED_APPROACH, timeline: "" });

		expect(check(next, wholeBody)).toMatchObject({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM,
					sectionKey: keyOf(PREVIOUS, "4. Timeline"),
					ordinal: 1,
				},
			],
		});
		expect(check(next, unscopedChat)).toEqual({ ok: true });
	});

	it("refuses a generated diagram dropped from its section", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH.replace(STEP_DIAGRAM, ""),
		});

		expect(check(next, wholeBody)).toEqual({
			ok: false,
			violations: [
				{
					code: PRESERVATION_VIOLATION.CHANGED_DIAGRAM,
					sectionKey: keyOf(PREVIOUS, "2. Approach"),
					ordinal: 0,
					visualId: STEP_ID,
					classification: { state: "generated", origin: "STEP" },
				},
			],
		});
	});

	it("allows a diagram moved to another section", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			team: lines(SECTIONS.team, "", PERSON_DIAGRAM),
			timeline: SECTIONS.timeline.replace(PERSON_DIAGRAM, ""),
		});

		expect(check(next, wholeBody)).toEqual({ ok: true });
	});

	it("allows a renamed heading that kept its diagram, and a new diagram", () => {
		const next = doc({
			approach: PERSON_EDITED_APPROACH,
			timeline: SECTIONS.timeline.replace(
				"## 4. Timeline",
				"## 4. Delivery timeline",
			),
			commercials: lines(
				SECTIONS.commercials,
				"",
				"```mermaid",
				"pie",
				'  "Build" : 70',
				'  "Run" : 30',
				"```",
			),
		});

		expect(check(next, wholeBody)).toEqual({ ok: true });
	});
});

describe("checkPreservation: normalisation", () => {
	const scopes: PreservationScope[] = [
		{ kind: "chat" },
		{ kind: "chat", patchedSectionKeys: [] },
		{ kind: "whole-body" },
		finding("4. Timeline"),
	];

	it.each(scopes)("passes identical bodies (%j)", (scope) => {
		expect(check(PREVIOUS, scope)).toEqual({ ok: true });
	});

	it.each(scopes)(
		"reads CRLF and LF copies as the same body (%j)",
		(scope) => {
			expect(
				check(PREVIOUS, scope, PREVIOUS.replace(/\n/g, "\r\n")),
			).toEqual({ ok: true });
		},
	);

	it("reads composed and decomposed text as the same body", () => {
		const composed = doc({
			context: SECTIONS.context.replace("Org", "Café"),
		});
		const decomposed = composed.normalize("NFD");

		expect(decomposed).not.toBe(composed);
		expect(check(decomposed, finding("4. Timeline"), composed)).toEqual({
			ok: true,
		});
	});
});

describe("sectionFingerprint", () => {
	const TEAM = keyOf(PREVIOUS, "3. Team");
	const COMMERCIALS = keyOf(PREVIOUS, "5. Commercials");

	it("changes with a link or an image destination the prose hash leaves out", () => {
		const relinked = doc({
			approach: PERSON_EDITED_APPROACH,
			team: SECTIONS.team.replace("/team", "/people"),
			commercials: SECTIONS.commercials.replace(
				"fees.png",
				"fees-v2.png",
			),
		});

		expect(sectionFingerprint(relinked, TEAM)).not.toBe(
			sectionFingerprint(PREVIOUS, TEAM),
		);
		expect(sectionFingerprint(relinked, COMMERCIALS)).not.toBe(
			sectionFingerprint(PREVIOUS, COMMERCIALS),
		);
	});

	it("is the same for a percent-encoded destination and a CRLF copy", () => {
		const previous = doc({ team: SECTIONS.team.replace("/team", "/café") });
		const encoded = doc({
			team: SECTIONS.team.replace("/team", "/caf%C3%A9"),
		}).replaceAll("\n", "\r\n");

		expect(sectionFingerprint(encoded, TEAM)).toBe(
			sectionFingerprint(previous, TEAM),
		);
	});

	it("changes with the section's prose and is undefined for a missing key", () => {
		const reworded = doc({
			approach: PERSON_EDITED_APPROACH,
			team: SECTIONS.team.replace("the people", "everyone"),
		});

		expect(sectionFingerprint(reworded, TEAM)).not.toBe(
			sectionFingerprint(PREVIOUS, TEAM),
		);
		expect(sectionFingerprint(PREVIOUS, "p1:missing#0")).toBeUndefined();
	});
});
